"""Original pixel font for the SNES's 8x8 CP1251 text cells.

Every stroke is an authored pixel. Nothing is rasterized, rescaled, or
thresholded from a vector font. Most letters use 5x7 pixels; wide Cyrillic
letters use seven columns and descenders may use the eighth row.
"""
