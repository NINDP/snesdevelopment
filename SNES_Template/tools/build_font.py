GLYPHS = {char: rows(pattern) for char, pattern in _PATTERNS.items()}
for destination, source in {
    'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H',
    'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X',
    'а': 'a', 'е': 'e', 'о': 'o', 'р': 'p', 'с': 'c', 'у': 'y', 'х': 'x',
    '\u00a0': ' ', '\u00ad': '-', '‘': "'", '’': "'", '‚': ',',
    '“': '"', '”': '"', '„': '"', '‹': '<', '›': '>',
}.items():
    GLYPHS[destination] = GLYPHS[source]


def glyph_pixels(char):
    """Two-bit UI pixels, centered within a stable eight-pixel advance."""
    pattern = GLYPHS[char]
    width = len(pattern[0])
    xoffset = (8-width)//2
    pixels = [2]*64
    for y, row in enumerate(pattern):
        for x, bit in enumerate(row):
            if bit == '1':
                pixels[y*8+xoffset+x] = 1
    return pixels


def _strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for child in value.values():
            yield from _strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from _strings(child)


def validate_content(path=None):
    path = path or ROOT/'assets/story.json'
    missing = sorted({char for text in _strings(json.loads(path.read_text()))
                      for char in text if not char.isspace() and char not in GLYPHS})
    if missing:
        raise ValueError('Missing bitmap glyphs: '+''.join(missing))


def font_tiles(planar):
    """Keep all 256 CP1251 tile IDs, including transparent tile zero."""
    validate_content()
    tiles = []
    for code in range(256):
        if code == 0:
            pixels = [0]*64
        elif code == 127:
            # DEL is never narrative text: a solid optical calibration tile.
            pixels = [1]*64
        elif code < 32:
            pixels = [2]*64
        else:
            try:
                char = bytes((code,)).decode('cp1251')
            except UnicodeDecodeError:
                char = '?'
            pixels = glyph_pixels(char if char in GLYPHS else '?')
        tiles.append(planar(pixels, 2))
    return tiles


def render_text(text, width=256, height=224):
    image = Image.new('RGB', (width, height), (8, 16, 24))
    for y, line in enumerate(text.split('\n')):
        for x, char in enumerate(line):
            pixels = glyph_pixels(char)
            for row in range(8):
                for column in range(8):
                    if pixels[row*8+column] == 1 and x*8+column < width and y*8+row < height:
                        image.putpixel((x*8+column,y*8+row), (232, 232, 208))
    return image


