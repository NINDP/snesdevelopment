ROOT = Path(__file__).resolve().parents[1]


def rows(pattern):
    result = tuple(pattern.split('/'))
    width = len(result[0])
    if not 1 <= width <= 7 or len(result) > 8:
        raise ValueError('Glyph outside 7x8 pixel bounds: '+pattern)
    if any(len(row) != width or set(row) - {'0', '1'} for row in result):
        raise ValueError('Malformed pixel glyph: '+pattern)
    return result


